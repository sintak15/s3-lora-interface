#!/usr/bin/env python3
"""Build offline LVGL alpha masks and web paths from the pinned Material SVGs.

Requires Pillow and Playwright with Chromium. No network access is used.
"""
import argparse
import base64
import hashlib
import io
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path

from PIL import Image
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / 'src/vendor/material-symbols'
START = '// BEGIN GENERATED MATERIAL ICONS'
END = '// END GENERATED MATERIAL ICONS'


def generate():
    manifest = json.loads((VENDOR/'manifest.json').read_text(encoding='utf-8'))
    paths, svgs = {}, {}
    for name, source in manifest['icons'].items():
        data = (VENDOR/f'{name}.svg').read_bytes()
        assert hashlib.sha256(data).hexdigest() == source['sha256'], f'{name}: source hash differs'
        tree = ET.fromstring(data)
        nodes = list(tree)
        assert nodes and all(node.tag.endswith('}path') for node in nodes)
        paths[name] = dict(viewBox=tree.attrib['viewBox'], path=' '.join(n.attrib['d'] for n in nodes))
        svgs[name] = data.decode('utf-8')
    header = ['// Generated by tools/generate_ui_icons.py. Do not edit.',
              '// Material Symbols Rounded, Copyright Google LLC, Apache-2.0.',
              '// See vendor/material-symbols/LICENSE.txt and manifest.json.',
              '#pragma once', '#include <lvgl.h>', '', 'namespace UiIcons {',
              'enum class Id { ' + ', '.join(name.title() for name in paths) + ' };']
    total = 0
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        page = browser.new_page()
        for name, svg in svgs.items():
            for size in (16, 20, 24):
                png = page.evaluate('''async ({svg,size}) => {
                  const image = new Image();
                  image.src='data:image/svg+xml;base64,'+btoa(svg);
                  await image.decode();
                  const canvas=document.createElement('canvas');
                  canvas.width=canvas.height=size*4;
                  canvas.getContext('2d').drawImage(image,0,0,size*4,size*4);
                  return canvas.toDataURL('image/png').split(',')[1];
                }''', dict(svg=svg, size=size))
                alpha = Image.open(io.BytesIO(base64.b64decode(png))).getchannel('A')
                alpha = alpha.resize((size,size), Image.Resampling.LANCZOS)
                pixels = list(alpha.get_flattened_data() if hasattr(alpha,'get_flattened_data') else alpha.getdata())
                packed = bytes((pixels[i]>>4)<<4 | (pixels[i+1]>>4) for i in range(0,len(pixels),2))
                assert max(packed)>0, f'{name}: empty icon'
                symbol = f'{name}_{size}'
                header += [f'static const uint8_t {symbol}_pixels[] = {{']
                header += ['  '+','.join(f'0x{x:02x}' for x in packed[i:i+20])+',' for i in range(0,len(packed),20)]
                header += ['};', f'static const lv_img_dsc_t {symbol} = {{',
                           f'  .header = {{.cf=LV_IMG_CF_ALPHA_4BIT,.always_zero=0,.reserved=0,.w={size},.h={size}}},',
                           f'  .data_size=sizeof({symbol}_pixels), .data={symbol}_pixels', '};']
                total += len(packed)
        browser.close()
    header += ['inline const lv_img_dsc_t* image(Id id, unsigned size=20) {', '  switch (id) {']
    for name in paths:
        header += [f'    case Id::{name.title()}: return size==16 ? &{name}_16 : size==24 ? &{name}_24 : &{name}_20;']
    header += ['  }', '  return nullptr;', '}', '} // namespace UiIcons', '']
    web = (ROOT/'src/WebUi.h').read_text(encoding='utf-8')
    block = START+'\nconst uiIconPaths='+json.dumps(paths,separators=(',',':'))+';\n'+END
    if START in web:
        web = re.sub(re.escape(START)+'.*?'+re.escape(END),lambda _:block,web,flags=re.S)
    else:
        web = web.replace('<script>\n','<script>\n'+block+'\n',1)
    return '\n'.join(header),web,total


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args = parser.parse_args()
    header,web,total = generate()
    for path,data in [(ROOT/'src/UiIcons.h',header),(ROOT/'src/WebUi.h',web)]:
        if args.check:
            assert path.read_text(encoding='utf-8') == data, f'{path.name}: regenerate icons'
        else:
            path.write_text(data,encoding='utf-8',newline='\n')
    print(f'28 Material Symbols at 16/20/24 px; {total:,} alpha-mask bytes; assets '+('verified' if args.check else 'generated'))
