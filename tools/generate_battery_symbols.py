from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
# Generate only three emboldened glyphs from the already-bundled OFL font.
out=['/* Generated by tools/generate_battery_symbols.py; Comic Neue, SIL OFL (ComicNeue-OFL.txt). */','#include <lvgl.h>']
for size in (10,12,14):
 font=ImageFont.truetype('src/fonts/ComicNeue-Regular.ttf',size)
 asc,desc=font.getmetrics(); bitmap=[]; glyphs=[(0,0,0,0,0,0)]
 for ch in '+-=':
  x0,y0,x1,y1=font.getbbox(ch,anchor='ls',stroke_width=1)
  w,h=x1-x0,y1-y0
  mask=Image.new('L',(w,h),0);ImageDraw.Draw(mask).text((-x0,-y0),ch,font=font,fill=255,anchor='ls',stroke_width=1,stroke_fill=255)
  pixels=list(mask.get_flattened_data() if hasattr(mask,"get_flattened_data") else mask.getdata());packed=[((pixels[i]>>4)<<4)|((pixels[i+1]>>4) if i+1<len(pixels) else 0) for i in range(0,len(pixels),2)]
  glyphs.append((len(bitmap),round((font.getlength(ch)+1)*16),w,h,x0,-y1));bitmap.extend(packed)
 prefix=f'battery_symbols_{size}'
 out.append(f'static const uint8_t {prefix}_bitmap[] = {{'+','.join(hex(x) for x in bitmap)+'};')
 out.append(f'static const lv_font_fmt_txt_glyph_dsc_t {prefix}_glyphs[] = {{')
 for idx,adv,w,h,x,y in glyphs:out.append(f'{{.bitmap_index={idx},.adv_w={adv},.box_w={w},.box_h={h},.ofs_x={x},.ofs_y={y}}},')
 out.append('};')
 out.append(f'static const uint16_t {prefix}_unicode[] = {{0,2,18}};')
 out.append(f'static const lv_font_fmt_txt_cmap_t {prefix}_cmap[] = {{{{.range_start=43,.range_length=19,.glyph_id_start=1,.unicode_list={prefix}_unicode,.glyph_id_ofs_list=NULL,.list_length=3,.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}}};')
 out.append(f'static lv_font_fmt_txt_glyph_cache_t {prefix}_cache;')
 out.append(f'static const lv_font_fmt_txt_dsc_t {prefix}_dsc = {{.glyph_bitmap={prefix}_bitmap,.glyph_dsc={prefix}_glyphs,.cmaps={prefix}_cmap,.kern_dsc=NULL,.kern_scale=0,.cmap_num=1,.bpp=4,.kern_classes=0,.bitmap_format=0,.cache=&{prefix}_cache}};')
 out.append(f'lv_font_t {prefix} = {{.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height={asc+desc},.base_line={desc},.subpx=LV_FONT_SUBPX_NONE,.underline_position=-1,.underline_thickness=1,.dsc=&{prefix}_dsc}};')
Path('src/fonts/battery_symbols.c').write_text('\n'.join(out)+'\n',encoding='ascii')
